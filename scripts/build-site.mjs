import { cp, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const siteDir = path.join(root, process.argv[2] ?? 'site');

// CI creates site/ by downloading artifacts. Locally, seed it from reports/ so the
// same index builder can be exercised without a workflow.
try {
  await readdir(siteDir);
} catch {
  await cp(path.join(root, 'reports'), siteDir, { recursive: true });
}

function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

const files = await readdir(siteDir);
const reports = files
  .filter((name) => name.endsWith('-report.html'))
  .map((name) => name.replace(/-report\.html$/, ''))
  .sort();

if (reports.length === 0) {
  throw new Error(`No k6 HTML reports found in ${siteDir}`);
}

for (const profile of reports) {
  for (const suffix of ['-report.html', '-summary.json', '-raw.json']) {
    try {
      await statFile(path.join(siteDir, `${profile}${suffix}`));
    } catch {
      throw new Error(`Missing artifact for ${profile}: ${suffix}`);
    }
  }
}

async function statFile(file) {
  await readFile(file);
}

const cards = reports
  .map((profile) => {
    const summaryPath = `${profile}-summary.json`;
    const rawPath = `${profile}-raw.json`;
    return `<article class="card">
      <h2>${escapeHtml(profile)}</h2>
      <p>Generated from a real k6 run against the local OpsBoard target.</p>
      <p><a href="${escapeHtml(`${profile}-report.html`)}">HTML report</a> · <a href="${escapeHtml(summaryPath)}">Summary JSON</a> · <a href="${escapeHtml(rawPath)}">Raw samples</a></p>
    </article>`;
  })
  .join('\n');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Enterprise QA Portfolio — k6 reports</title>
<style>
:root { color-scheme: dark; font-family: system-ui, sans-serif; --border: #293752; --muted: #9aa9c0; }
body { margin: 0; background: #0b1120; color: #e8eef8; }
main { width: min(980px, calc(100% - 40px)); margin: 0 auto; padding: 56px 0 80px; }
h1 { font-size: 42px; margin: 0 0 8px; letter-spacing: -0.03em; }
p.intro { color: var(--muted); font-size: 18px; line-height: 1.6; }
.cards { display: grid; grid-template-columns: repeat(auto-fit, minmax(260px, 1fr)); gap: 16px; margin-top: 32px; }
.card { border: 1px solid var(--border); border-radius: 16px; padding: 22px; background: #111a2c; }
.card h2 { margin: 0 0 10px; text-transform: capitalize; }
.card p { color: var(--muted); line-height: 1.5; }
a { color: #7dd3fc; }
code { color: #a7f3d0; }
footer { margin-top: 40px; color: var(--muted); font-size: 13px; }
</style>
</head>
<body>
<main>
<h1>Enterprise QA Portfolio</h1>
<p class="intro">Published k6 evidence. Each profile was executed against the local
<code>OpsBoard</code> application with pinned k6 ${escapeHtml(process.env.K6_VERSION ?? 'v2.4.0')};
the files below are generated by those runs, not hand-written.</p>
<div class="cards">${cards}</div>
<footer>Source: github.com/ManikandanK-QA/enterprise-qa-portfolio</footer>
</main>
</body>
</html>`;

await writeFile(path.join(siteDir, 'index.html'), html, 'utf8');
console.log(`site: generated index with ${reports.length} profiles in ${siteDir}`);
